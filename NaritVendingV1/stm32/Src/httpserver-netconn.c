static const char AUTH_HEADER[] =
"Authorization: Basic bmFyaXQ6UEBzc3cwcmQ=";

static uint8_t request_has_auth(const char *buf, u16_t buflen)
{
  size_t auth_len = strlen(AUTH_HEADER);
  u16_t index;

  if (buflen < auth_len)
  {
    return 0U;
  }

  for (index = 0U; index <= (u16_t)(buflen - auth_len); index++)
  {
    if (memcmp(&buf[index], AUTH_HEADER, auth_len) == 0)
    {
      return 1U;
    }
  }
  return 0U;
}

static void send_unauthorized(struct netconn *conn)
{
  static const char response[] =
      "HTTP/1.1 401 Unauthorized\r\nWWW-Authenticate: Basic realm=\"NUCLEO-F439ZI\"\r\n"
      "Content-Type: text/plain\r\nConnection: close\r\n\r\nAuthentication required";
  netconn_write(conn, response, sizeof(response) - 1U, NETCONN_COPY);
}

static uint8_t led_is_on(Led_TypeDef led)
{
  GPIO_TypeDef *port = LED1_GPIO_PORT;
  uint16_t pin = LED1_PIN;

  if (led == LED2)
  {
    port = LED2_GPIO_PORT;
    pin = LED2_PIN;
  }
  else if (led == LED3)
  {
    port = LED3_GPIO_PORT;
    pin = LED3_PIN;
  }
  return (HAL_GPIO_ReadPin(port, pin) == GPIO_PIN_SET) ? 1U : 0U;
}

static void send_led_status(struct netconn *conn)
{
  char response[192];
  int length = snprintf(response, sizeof(response),
      "HTTP/1.1 200 OK\r\nContent-Type: application/json\r\n"
      "Cache-Control: no-store\r\nConnection: close\r\n\r\n"
      "{\"green\":\"%s\",\"blue\":\"%s\",\"red\":\"%s\"}",
      led_is_on(LED1) ? "on" : "off",
      led_is_on(LED2) ? "on" : "off",
      led_is_on(LED3) ? "on" : "off");

  if (length > 0)
  {
    netconn_write(conn, response, (size_t)length, NETCONN_COPY);
  }
}

